export type Language = 'es' | 'en'

export function getLanguage(telegramLang: string | undefined): Language {
  // Si es español, usar español. Cualquier otro idioma = inglés
  return telegramLang === 'es' ? 'es' : 'en'
}

export function getTranslations(lang: Language) {
  return translations[lang]
}